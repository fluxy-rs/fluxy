#!/usr/bin/env node
// Keeps the frontend from drifting back into thousand-line components.
//
// The numbers alone do not make a file readable - a 200-line file of plain JSX
// can be clearer than a 140-line one with six nested conditionals. They are a
// proxy, chosen because they are the one property a machine can hold honestly.
// The rule that actually matters, and that a reviewer still has to apply, is in
// AGENTS.md: a file changes for one reason.
//
// Existing offenders are grandfathered through scripts/code-limits-baseline.json.
// The baseline may only shrink: a file that is already too long must not get
// longer, and a file that is not in the baseline must fit. The --update flag
// only rewrites entries for files that still violate, so a split removes itself.

import { readFile, writeFile, readdir } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { parse } from "@babel/parser";

const LIMITS = {
  /** A .tsx file, tests excluded. */
  component: 250,
  /** A .ts file: a hook, a helper module, a store. */
  module: 300,
  /** One function body, nested functions counted separately. */
  body: 120,
  /**
   * Nested JSX elements, so a wall of divs fails even when each line is short.
   *
   * Ten, not six: measuring the codebase at six flagged ordinary cards and
   * lists - a title, an icon and two wrappers reach it - and a limit that
   * catches everything teaches people to ignore the gate. What it is meant to
   * catch is a component five screens deep in its own JSX.
   */
  jsx: 10,
};

/** Data, not behaviour: counting its lines says nothing about maintainability. */
const EXEMPT_FILES = new Set([
  // The translation catalogue: a table, not code.
  "src/i18n/index.tsx",
  // Generated by the runtime, never edited by hand.
  "src/bindings.ts",
]);

/** Vendored from neut/ui and kept verbatim, comments included. */
const VENDORED = ["src/ui/"];

const BASELINE = "scripts/code-limits-baseline.json";

function toPosix(path) {
  return path.split(sep).join("/");
}

async function walk(dir, out = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === "dist") continue;
      await walk(path, out);
    } else if (/\.(ts|tsx)$/.test(entry.name) && !/\.test\.(ts|tsx)$/.test(entry.name)) {
      out.push(path);
    }
  }
  return out;
}

function lineCount(source) {
  const lines = source.split("\n");
  return lines[lines.length - 1] === "" ? lines.length - 1 : lines.length;
}

function functionName(node) {
  if (node.id && node.id.name) return node.id.name;
  const parent = node.parent;
  if (!parent) return "<anonymous>";
  if (parent.type === "VariableDeclarator" && parent.id && parent.id.name) return parent.id.name;
  if (parent.type === "ObjectProperty" && parent.key && parent.key.name) return parent.key.name;
  return "<anonymous>";
}

export function analyze(source, filename) {
  const ast = parse(source, {
    sourceType: "module",
    plugins: ["typescript", "jsx"],
    errorRecovery: true,
  });

  const bodies = [];
  let depth = 0;
  let maxDepth = 0;

  const visit = (node, parent) => {
    if (!node || typeof node.type !== "string") return;
    node.parent = parent;

    const isFunction =
      node.type === "FunctionDeclaration" ||
      node.type === "FunctionExpression" ||
      node.type === "ArrowFunctionExpression";

    if (isFunction && node.body && node.body.type === "BlockStatement") {
      const span = node.body.loc.end.line - node.body.loc.start.line + 1;
      bodies.push({ name: functionName(node), line: node.loc.start.line, lines: span });
    }

    const isJsx =
      node.type === "JSXElement" ||
      node.type === "JSXFragment" ||
      node.type === "JSXSelfClosingElement";

    if (isJsx) {
      depth += 1;
      if (depth > maxDepth) maxDepth = depth;
    }

    for (const key of Object.keys(node)) {
      if (key === "parent" || key === "loc" || key === "leadingComments") continue;
      const value = node[key];
      if (Array.isArray(value)) {
        for (const child of value) {
          if (child && typeof child.type === "string") visit(child, node);
        }
      } else if (value && typeof value.type === "string") {
        visit(value, node);
      }
    }

    if (isJsx) depth -= 1;
  };

  visit(ast.program, null);

  let maxBody = { name: "<none>", line: 0, lines: 0 };
  for (const body of bodies) {
    if (body.lines > maxBody.lines) maxBody = body;
  }

  return { file: filename, lines: lineCount(source), maxBody: maxBody, jsxDepth: maxDepth };
}

function limitsFor(file) {
  return {
    lines: file.endsWith(".tsx") ? LIMITS.component : LIMITS.module,
    body: LIMITS.body,
    jsx: LIMITS.jsx,
  };
}

async function measure(root) {
  const files = (await walk(join(root, "src"))).map(function (path) {
    return toPosix(relative(root, path));
  });
  files.sort();
  const results = [];
  for (const file of files) {
    if (EXEMPT_FILES.has(file)) continue;
    const source = await readFile(join(root, file), "utf8");
    try {
      const result = analyze(source, file);
      result.limits = limitsFor(file);
      results.push(result);
    } catch (error) {
      results.push({ file: file, error: error.message });
    }
  }
  return results;
}

function violationsFor(result, baseline) {
  if (result.error) {
    return [{ file: result.file, metric: "parse", measured: 0, allowed: 0, note: result.error }];
  }
  const allowance = baseline[result.file] || {};
  const found = [];

  const allowedLines = Math.max(result.limits.lines, allowance.lines || 0);
  if (result.lines > allowedLines) {
    found.push({
      file: result.file,
      metric: "lines",
      measured: result.lines,
      allowed: allowedLines,
      note: allowance.lines ? "already over; it may not grow" : "new file",
    });
  }

  const allowedBody = Math.max(result.limits.body, allowance.body || 0);
  if (result.maxBody.lines > allowedBody) {
    found.push({
      file: result.file,
      metric: "function",
      measured: result.maxBody.lines,
      allowed: allowedBody,
      note: result.maxBody.name + " at line " + result.maxBody.line,
    });
  }

  const allowedJsx = Math.max(result.limits.jsx, allowance.jsx || 0);
  if (result.jsxDepth > allowedJsx) {
    found.push({
      file: result.file,
      metric: "jsx depth",
      measured: result.jsxDepth,
      allowed: allowedJsx,
      note: "nested elements",
    });
  }

  return found;
}

function selfTest() {
  const longBody = analyze(
    "export function A() {\n" + "  const x = 1;\n".repeat(LIMITS.body + 5) + "}\n",
    "fixture.ts",
  );
  const nested = analyze(
    "const view = <a><b><c><d><e><f><g /></f></e></d></c></b></a>;\n",
    "fixture.tsx",
  );
  const fine = analyze("export const x = 1;\n", "fixture.ts");

  const checks = [
    ["a long body is measured", longBody.maxBody.lines > LIMITS.body],
    ["jsx depth is measured", nested.jsxDepth >= 7],
    ["a small file passes", fine.lines === 1 && fine.maxBody.lines === 0],
  ];

  let failed = 0;
  for (const check of checks) {
    if (!check[1]) {
      console.error("self-test failed: " + check[0]);
      failed += 1;
    }
  }
  return failed === 0;
}

async function main() {
  const args = new Set(process.argv.slice(2));

  if (args.has("--self-test")) {
    if (!selfTest()) process.exit(1);
    console.log("code limits: self-test ok");
    return;
  }

  const root = process.cwd();
  const results = await measure(root);

  if (args.has("--update")) {
    const baseline = {};
    for (const result of results) {
      if (result.error) continue;
      if (violationsFor(result, {}).length === 0) continue;
      baseline[result.file] = {
        lines: result.lines,
        body: result.maxBody.lines,
        jsx: result.jsxDepth,
      };
    }
    await writeFile(join(root, BASELINE), JSON.stringify(baseline, null, 2) + "\n");
    console.log(
      "code limits: baseline rewritten with " + Object.keys(baseline).length + " file(s)",
    );
    return;
  }

  let baseline = {};
  try {
    baseline = JSON.parse(await readFile(join(root, BASELINE), "utf8"));
  } catch {
    baseline = {};
  }

  const violations = [];
  for (const result of results) {
    for (const violation of violationsFor(result, baseline)) violations.push(violation);
  }

  const stale = Object.keys(baseline).filter(function (file) {
    return !results.some(function (result) {
      return result.file === file;
    });
  });
  if (stale.length > 0) {
    console.warn(
      "code limits: " +
        stale.length +
        " baseline entry(ies) point at files that are gone; --update prunes them",
    );
  }

  if (violations.length === 0) {
    console.log(
      "code limits: " +
        results.length +
        " files, " +
        Object.keys(baseline).length +
        " grandfathered",
    );
    return;
  }

  for (const item of violations) {
    console.error(
      item.file +
        "  " +
        item.metric +
        "  " +
        item.measured +
        " > " +
        item.allowed +
        "  " +
        (item.note || ""),
    );
  }
  console.error("\nSplit the file, or lower the baseline if it is genuinely still the same size.");
  process.exit(1);
}

const invoked = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (invoked) {
  await main();
}
