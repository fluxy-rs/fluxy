function readLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "zh-CN" || stored === "en") {
      return stored;
    }
  } catch {
    // Use the product default.
  }
  return "zh-CN";
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}

export function I18nProvider(props: ParentProps) {
  const [locale, setLocaleSignal] = createSignal<Locale>(readLocale());

  createEffect(() => {
    document.documentElement.lang = locale();
  });

  const setLocale = (next: Locale) => {
    setLocaleSignal(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // The current session still uses the selected locale.
    }
  };

  const t = (key: string, vars?: Record<string, string | number>) => {
    const template = messages[locale()][key] ?? messages["zh-CN"][key] ?? key;
    return interpolate(template, vars);
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>{props.children}</I18nContext.Provider>
  );
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}
